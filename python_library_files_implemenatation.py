import pandas as pd

data = {
    "Name": ["Arun", "Priya", "Rahul", "Arun", "Sneha", "Karthik", "Priya"],
    "Department": ["ECE", "CSE", "ECE", "ECE", "EEE", "CSE", "CSE"],
    "Marks": [85, 72, 91, 85, 65, 78, 72],
    "Attendance": [92, 85, 96, 92, 75, 88, 85]
}

df = pd.DataFrame(data)

print("ORIGINAL DATA")
print(df)

print("\nFILTERING DATA")
result1 = df[df["Marks"] > 80]
print(result1)

print("\nSORTING DATA BY MARKS")
result2 = df.sort_values("Marks", ascending=False)
print(result2)

print("\nREMOVING DUPLICATES")
result3 = df.drop_duplicates()
print(result3)

